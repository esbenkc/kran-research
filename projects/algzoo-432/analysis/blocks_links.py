"""C3 entry-level link table (Iris). Run after ablate.py:
    .venv/bin/python blocks_links.py  -> blocks_links.md

For every target row (W_hh row i, W_oh row k) list the entries that carry >= 80% of the row's mean
|W_ij h_j| contribution (seed 3, n = 1e5, all steps), with sign, share, zero/+1% disagreement from
ablate.json and a link role. The remaining entries of the row are listed as 'distributed' with their
summed share and max single-entry zero-ablation disagreement.
"""
import json

import numpy as np

from core import load_raw

Wi, Wh, Wo = load_raw()
N = 100_000
x = np.random.default_rng(3).standard_normal((N, 10))
abl = json.load(open("ablate.json"))
DIS = {(r["block"], r["i"], r["j"], r["kind"]): r["dis"] for r in abl["rows"]}

SHORT = {0: "lag2-timer", 1: "deficit-lag2", 2: "leaky-max", 4: "max-incr", 5: "top2-cmp",
         6: "deficit-lag1", 7: "max-minus-x", 8: "deficit-lag3+", 9: "newmax-gate"}
SHORT.update({3: "clock2-B3", 10: "val/clock-B10", 11: "val/clock-B11", 12: "val/clock-B12",
              13: "clock2-B13", 14: "val/clock-B14", 15: "clock2-B15"})

# Hand-checked link roles (sources: subA.md s.2, denseB2.md). Others get "src -> tgt (excite/inhibit)".
LINK = {
    ("hh", 2, 2): "leak: running max kept with gain 0.969/step",
    ("hh", 2, 4): "accumulate: add new-max increment into running max",
    ("hh", 4, 2): "compare x with scaled old max (0.852)",
    ("hh", 4, 4): "compare x with last increment (0.986)",
    ("hh", 7, 2): "max-minus-x: old max part (0.899)",
    ("hh", 7, 4): "max-minus-x: increment part (1.016)",
    ("hh", 6, 2): "deficit lag 1: old max without last input",
    ("hh", 1, 2): "deficit lag 2: max part",
    ("hh", 1, 4): "deficit lag 2: increment part",
    ("hh", 1, 6): "shift register: lag-1 deficit -> lag-2",
    ("hh", 8, 2): "deficit lag>=3: max part",
    ("hh", 8, 1): "shift register: lag-2 deficit -> lag>=3",
    ("hh", 8, 8): "deficit lag>=3 decay (0.6/step)",
    ("hh", 9, 7): "VETO: x_{t-1} below running max -> gate off",
    ("hh", 9, 8): "veto (deficit lag>=3)",
    ("hh", 9, 4): "drive: new-max increment turns gate on",
    ("hh", 5, 7): "VETO: x_{t-1} below max",
    ("hh", 5, 8): "VETO: x_{t-1} below ~2nd max",
    ("hh", 5, 4): "drive: new-max increment",
    ("hh", 0, 5): "lag-2 delay: previous top-2 event turns timer off",
    ("hh", 0, 9): "lag-2 delay: previous new-max event turns timer off",
    ("oh", 8, 5): "vote: x_8 was top-2 -> logit 8",
}


def states():
    h = np.zeros((N, 16))
    hs = []
    for t in range(10):
        hs.append(h)
        h = np.maximum(h @ Wh.T + x[:, t : t + 1] * Wi[None, :], 0.0)
    return np.stack(hs, 1), h  # (N,10,16) pre-step states, final state


def row_table(name, contrib_abs, contrib_signed, wrow, block, i, label):
    tot = contrib_abs.sum()
    order = np.argsort(-contrib_abs)
    out, cum = [], 0.0
    lines = [f"\n### {label}\n", "| entry | w (raw) | sign | share | zero dis % | +1% dis % | role |", "|---|---|---|---|---|---|---|"]
    kept = []
    for j in order:
        if cum >= 0.8:
            break
        cum += contrib_abs[j] / tot
        kept.append(j)
    for j in kept:
        key = ("hh" if block == "W_hh" else "oh", i, j)
        sign = "+" if contrib_signed[j] > 0 else "−"
        role = LINK.get(key, f"{SHORT[j]} -> {SHORT[i] if block == 'W_hh' else 'logit ' + str(i)} ({'excite' if sign == '+' else 'inhibit'})")
        lines.append(
            f"| {block}[{i},{j}] | {wrow[j]:+.3f} | {sign} | {contrib_abs[j] / tot:.2f} | "
            f"{DIS[(block, i, j, 'zero')]:.1f} | {DIS[(block, i, j, 'pert')]:.2f} | {role} |"
        )
    rest = [j for j in range(16) if j not in kept]
    if rest:
        share = contrib_abs[rest].sum() / tot
        mz = max(DIS[(block, i, j, "zero")] for j in rest)
        lines.append(f"| distributed: {len(rest)} entries ({', '.join(map(str, rest))}) | | | {share:.2f} | max {mz:.1f} | | small links; each listed in ablate.json |")
    return lines


def main():
    hs, hf = states()
    md = ["# C3 entry-level links (generated by blocks_links.py; seed 3, n = 1e5)",
          "",
          "share = entry's mean |W_ij h_j| / row total. dis = disagreement with model argmax (ablate.json).",
          "Neuron short names: " + ", ".join(f"{k}={v}" for k, v in SHORT.items()) + "."]
    md.append("\n## W_hi (16)\n")
    md.append("| n | w (raw) | zero dis % | +1% dis % | role |")
    md.append("|---|---|---|---|---|")
    for n in range(16):
        role = "main input (|w| > 10)" if abs(Wi[n]) > 10 else ("moderate input" if abs(Wi[n]) > 1 else "small direct input")
        md.append(f"| W_hi[{n}] ({SHORT[n]}) | {Wi[n]:+.3f} | {DIS[('W_hi', n, None, 'zero')]:.1f} | {DIS[('W_hi', n, None, 'pert')]:.2f} | {role} |")
    md.append("\n## W_hh (256), one table per target neuron\n")
    for i in range(16):
        c = hs * Wh[i][None, None, :]
        md += row_table("W_hh", np.abs(c).mean((0, 1)), c.mean((0, 1)), Wh[i], "W_hh", i, f"target n{i} ({SHORT[i]})")
    md.append("\n## W_oh (160), one table per logit\n")
    for k in range(10):
        c = hf * Wo[k][None, :]
        md += row_table("W_oh", np.abs(c).mean(0), c.mean(0), Wo[k], "W_oh", k, f"logit {k}")
    open("blocks_links.md", "w").write("\n".join(md) + "\n")
    print("wrote blocks_links.md", len(md), "lines")


if __name__ == "__main__":
    main()
