"""results/analysis.json -> proof-matrix.md (PREREG s6). Lines after the SKEPTIC marker are kept as they are.

    uv run python proof_matrix.py

Seeds = seed blocks b = i mod 3 (s0, s1, s2). Headline rows: the 3 status cells' err per seed block and the fr
differences (anchor - md, bare - md) per model per block, one variant name per arm. Pooled rows have seed '-' and the
claim 'pooled'. Controls: the visible-link gate per model per block, the visible-link list filler per block, and the
two nulls (pooled, seed '-'). Every artifact cell is ONE path relative to this folder.
"""
from __future__ import annotations

import json
from fractions import Fraction as F
from pathlib import Path

PROJ = Path(__file__).resolve().parent
MARK = "<!-- SKEPTIC ROWS: everything below this line is kept by proof_matrix.py -->"
STATUS_CELLS = [("A", "md"), ("A", "anchor"), ("B", "raw")]


def v(x, signed=False):
    if x is None:
        return "n/a"
    y = x["value"] if isinstance(x, dict) else float(x)
    return f"{y:+.3f}" if signed else f"{y:.3f}"


def main() -> None:
    res = json.loads((PROJ / "results" / "analysis.json").read_text())
    jobs = res["jobs"]
    models = res["models"]
    cells = {(c["slot"], c["cell"]): c for c in res["cells"]}
    raw_dir = lambda m, cell: f"{jobs[m]}/raw/{cell}"
    out = ["# Proof matrix — anchor-text-law", "",
           f"Generated by `proof_matrix.py` from `results/analysis.json` (status {res['status']['status']}). Seeds are the",
           "pre-registered seed blocks b = i mod 3 (s0, s1, s2); every block holds the same number of runs per cell.", "",
           "| claim | seed | variant | control | result | artifact |", "|---|---|---|---|---|---|"]
    for m, f in STATUS_CELLS:
        h = res["heldout"][f"{m}-{f}"]
        name = f"err {f} {models[m]}"
        blocks = h["err_seed"]["blocks"] if h.get("err_seed") else [None] * 3
        for b in range(3):
            pb = cells[m, f"{f}-free"]["per_block"][str(b)]
            out.append(f"| headline | s{b} | {name} | none | err {v(blocks[b], True)} (followed {pb['followed']} of {pb['n']}) "
                       f"| {raw_dir(m, f + '-free')} |")
        c = cells[m, f"{f}-free"]
        out.append(f"| pooled | - | {name} | none | catch {c['followed']} of {c['n']} = {v(h['catch'])}, pred {v(h['pred'])}, "
                   f"err {v(h['err'], True)} [{v(h['err_ci'][0], True)}, {v(h['err_ci'][1], True)}] (bootstrap) | results/analysis.json |")
    for m in "AB":
        for name in ("anchor_md", "bare_md"):
            d = res["fr_diffs"][m][name]
            label = {"anchor_md": "fr anchor minus md", "bare_md": "fr bare minus md"}[name] + f" {models[m]}"
            blocks = d["seed"]["blocks"] if d.get("seed") else [None] * 3
            for b in range(3):
                out.append(f"| headline | s{b} | {label} | none | {v(blocks[b], True)} | results/analysis.json |")
            out.append(f"| pooled | - | {label} | none | {v(d['value'], True)} [{v(d['ci'][0], True)}, {v(d['ci'][1], True)}] "
                       f"(bootstrap) | results/analysis.json |")
    for m in "AB":
        for fmt in ("raw", "md", "bare", "anchor"):
            c = cells.get((m, f"{fmt}-free"))
            if not c:
                continue
            for b in range(3):
                pb = c["per_block"][str(b)]
                out.append(f"| cells | s{b} | {fmt} {models[m]} | none | reached {pb['reached']} of {pb['n']}, followed "
                           f"{pb['followed']}, followed after reach {pb['followed_reached']} | {raw_dir(m, fmt + '-free')} |")
    for m in "AB":
        for cell, ctl in (("raw-none", "visible-link gate"), ("bare-none", "visible link in bare list"),
                          ("anchor-none", "visible link in anchor list")):
            c = cells.get((m, cell))
            if not c:
                continue
            for b in range(3):
                pb = c["per_block"][str(b)]
                if pb["n"]:
                    out.append(f"| control | s{b} | {cell} {models[m]} | {ctl} | followed {pb['followed']} of {pb['n']} "
                               f"| {raw_dir(m, cell)} |")
    for k, n in res["nulls"].items():
        m, f = k.split("-")
        out.append(f"| null | - | err {f} {models[m]} | format-blind null | pred {v(n['format_blind_pred'])}, err "
                   f"{v(n['format_blind_err'], True)} | results/analysis.json |")
        out.append(f"| null | - | err {f} {models[m]} | constant null | pred {v(n['constant_pred'])}, err "
                   f"{v(n['constant_err'], True)} | results/analysis.json |")
    out.append("")
    for m, f in STATUS_CELLS:
        h = res["heldout"][f"{m}-{f}"]
        t = h["err_seed"]["t"] if h.get("err_seed") else None
        if t:
            out.append(f"- seed-level: err {f} {models[m]} {t[0]:+.3f} [{t[1]:+.3f}, {t[2]:+.3f}] (t-interval over 3 seed blocks, df 2)")
    for m in "AB":
        for name in ("anchor_md", "bare_md"):
            t = res["fr_diffs"][m][name]["seed"]["t"] if res["fr_diffs"][m][name].get("seed") else None
            if t:
                out.append(f"- seed-level: {name.replace('_', ' minus ')} fr {models[m]} {t[0]:+.3f} [{t[1]:+.3f}, {t[2]:+.3f}] "
                           f"(t-interval over 3 seed blocks, df 2)")
    out += ["", MARK]
    path = PROJ / "proof-matrix.md"
    old = path.read_text() if path.exists() else ""
    tail = old.split(MARK, 1)[1] if MARK in old else "\n"
    path.write_text("\n".join(out) + tail)
    print("wrote", path)


if __name__ == "__main__":
    main()
