"""Write proof-matrix.md (one row per cell: | claim | seed | variant | control | result | artifact |) from the saved
results: data/results/results.json (analysis.py), data/results/repro_*.json, data/fits/cut_grid.json.
Artifacts are paths relative to the project folder. Skeptics append their rebuild rows below the generated table.
Usage: python3 make_proof_matrix.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
R = json.loads((ROOT / "data/results/results.json").read_text())
G = json.loads((ROOT / "data/fits/cut_grid.json").read_text())
rows = []


def add(claim, seed, variant, control, result, artifact):
    rows.append(f"| {claim} | {seed} | {variant} | {control} | {result} | {artifact} |")


k = G["kstar"]
kr = next(r for r in G["rows"] if r["k"] == k)
add("clean catch survives the cut", "-", f"cut probe, k={k}", "none",
    f"OOF fit-pool catch {kr['proj']['oof_catch']:.3f}, eval catch {kr['proj']['eval_catch']:.3f}", "data/fits/cut_grid.json")
add("clean catch survives the cut", "-", f"random-cut probe, k={k}", "random subspace (rank-matched)",
    f"OOF {kr['rand']['draws'][kr['rand']['control_draw']]['oof_catch']:.3f}, eval "
    f"{kr['rand']['draws'][kr['rand']['control_draw']]['eval_catch']:.3f}, draws used {kr['rand']['draws_used']}", "data/fits/cut_grid.json")
add("clean catch survives the cut", "-", "full probe", "none", f"eval catch {G['eval_catch_unproj']:.3f}", "data/fits/cut_grid.json")
add("clean catch survives the cut", "-", f"literal removal P_F w, k={k}", "variant (not attacked)",
    f"eval catch {kr['lit_eval_catch']:.3f}", "data/fits/cut_grid.json")
for f in sorted((ROOT / "data/results").glob("repro_*.json")):
    rp = json.loads(f.read_text())
    add("attack code reproduces theory-1023", rp["run"].split("seed")[-1], f"full probe, step {rp['step']}", "repro of 1023 s0",
        f"country-token KL {rp['new']['kl_country']:.4f} vs {rp['theory1023']['kl_country']:.4f} (ratio {rp['kl_country_ratio']:.2f}), "
        f"catch {rp['new']['catch']:.3f} vs {rp['theory1023']['catch']:.3f}, score corr {rp['eval_score_corr']:.3f}",
        f"data/results/{f.name}")
names = {"unproj": "full probe", "proj": "cut probe", "rand": "random-cut probe"}
for arm, A in R["arms"].items():
    for seed, ps in A["per_seed"].items():
        fin = ps["final"]
        src = f"data/runs1023/r29__lam10000__seed{seed[-1]}/" if seed.startswith("1023") else f"data/runs/{arm}__lam10000__seed{seed[3:]}/"
        add("headline: price", seed, names[arm], "control" if arm == "rand" else ("baseline" if arm == "unproj" else "none"),
            f"price {ps['price']:.4g} (first crossing {ps['first_cross']:.4g}); step {fin['step']}: catch {fin['catch']:.3f}, "
            f"country-token KL {fin['kl_country']:.4f}, all-token KL {fin['kl_all']:.4f}, right-first {fin.get('right_first', '-')}/298",
            src + "ckpt_*.npz")
    add("headline: price (pooled)", "pooled", names[arm], "-",
        f"price {A['price']:.4g}, final pooled catch {A['final_pooled_catch']:.3f}, seeds {len(A['seeds'])}",
        "data/results/results.json")
if "status" in R:
    S = R["status"]
    add("headline: status (PREREG s7 + D7/D8)", "pooled", "P vs U vs R", "R = control",
        f"{S['status']}: P/U {S['ratio_P_U']}, R/U {S['ratio_R_U']}, R falls within 1.5x: {S['r_falls_within_1.5x']}",
        "data/results/results.json")
out = ["# Proof matrix: curvature-cut-probe", "",
       "Generated by `make_proof_matrix.py` from the saved results. Skeptics add their rebuild rows at the end.", "",
       "| claim | seed | variant | control | result | artifact |", "|---|---|---|---|---|---|"] + rows
p = ROOT / "proof-matrix.md"
old = p.read_text() if p.exists() else ""
tail = old.split("<!-- skeptic rows -->", 1)[1] if "<!-- skeptic rows -->" in old else "\n"
p.write_text("\n".join(out) + "\n\n<!-- skeptic rows -->" + tail)
print(p.read_text()[:3000])
