"""Write proof-matrix.md from results/analysis_counted.json (+ screen, smoke, viewcheck, cue checks).

    python3 proof_matrix.py

One row per cell: | claim | seed | variant | control | result | artifact |. 'seed' = the run indices of the cell (each run
is a fresh site with fresh random link addresses; API models sample at the provider's default temperature).
Skeptics append their rebuild rows below the generated table (the script keeps everything after the marker line).
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
SHORT = {"gpt-5.4-mini": "mini", "gemini-3.5-flash-lite": "fl35", "gemini-3.1-flash-lite": "fl31"}
NAME = {"gpt-5.4-mini": "GPT-5.4 mini", "gemini-3.5-flash-lite": "Gemini 3.5 Flash-Lite", "gemini-3.1-flash-lite": "Gemini 3.1 Flash-Lite"}
MARK = "<!-- skeptic rows below: kept on regeneration -->"
ROLE = {"A": ("law: positive control", "positive control (inline style + aria-hidden)"),
        "A2": ("law: cue cell", "none"), "C": ("law: cue cell", "none"),
        "E": ("law: false cue on a visible link", "visible-link control"),
        "B": ("headline", "none"), "B2": ("headline", "none")}


def pct(x: float) -> str:
    return f"{100 * x:.0f}%"


def main() -> None:
    an = json.loads((ROOT / "results" / "analysis_counted.json").read_text())
    rows = []
    for c in ("B", "B2", "A", "A2", "C", "E"):
        claim, control = ROLE[c]
        cell = an["cells"][c]
        for m in an["agents"]:
            d = cell["agents"][m]
            rows.append((claim, "runs 0-39", f"{NAME[m]}, cell {c}", control,
                         f"neutral {d['neutral']['k']}/{d['neutral']['n']}, stacked {d['stacked']['k']}/{d['stacked']['n']}; "
                         f"cut {d['cut']:+.3f} [{d['cut_ci'][0]:+.3f}, {d['cut_ci'][1]:+.3f}]; cue in view {d['stacked']['cue']}/{d['stacked']['n']}",
                         f"results/cells/counted__{c}__{SHORT[m]}.json"))
        p = cell["pooled"]
        rows.append((claim, "runs 0-39", f"pooled (3 agents equal), cell {c}", control,
                     f"stacked follows {pct(p['stacked']['rate'])} [{pct(p['stacked']['ci'][0])}, {pct(p['stacked']['ci'][1])}]; "
                     f"cut {p['cut']:+.3f} [{p['cut_ci'][0]:+.3f}, {p['cut_ci'][1]:+.3f}]",
                     f"results/cells/counted__{c}__pooled.json"))
    for c in ("B", "B2", "A", "A2", "C", "E"):
        for m in an["agents"]:
            d = an["cells"][c]["agents"][m]
            rows.append(("null: no arm effect", "10,000 permutations", f"{NAME[m]}, cell {c}", "label shuffle within template",
                         f"two-sided p = {d['shuffle_p']} for cut {d['cut']:+.3f}", f"results/cells/counted__{c}__{SHORT[m]}.json"))
    rows.append(("status (PREREG s5)", "all", "B and B2, 3 agents", "gate on A",
                 f"{an['status']}; gate agents {[SHORT[m] for m in an['gate']['agents']]}; NO reasons {len(an['no_reasons'])}",
                 "results/analysis_counted.json"))
    rows.append(("prereg outcome", "all", "legs i-iv", "none", f"{an['prereg_outcome']}: {json.dumps(an['prereg_legs'])}",
                 "results/analysis_counted.json"))
    # screen
    scr = ROOT / "web" / "results" / "summary_screen_raw_screen.json"
    if scr.exists():
        for s in json.loads(scr.read_text()):
            rows.append(("agent screen (excluded)", "runs 0-9", f"{s['model']}, {s['cell']}", "none",
                         f"follows {s['fit']}/{s['n']}", "web/results/summary_screen_raw_screen.json"))
    vc = ROOT / "viewcheck" / "viewcheck.json"
    if vc.exists():
        v = json.loads(vc.read_text())
        for c in ("A", "A2", "C", "B", "B2", "E", "OFF", "ZERO"):
            rs = [r for r in v if r["hiding"] == c]
            rows.append(("human and assistive views", "5 templates", f"cell {c}", "model-free (Chromium)",
                         f"a11y {sum(r['a11y'] for r in rs)}/{len(rs)}, Tab {sum(r['tab'] for r in rs)}/{len(rs)}, "
                         f"print {sum(r['print'] for r in rs)}/{len(rs)}, pixels {sum(r['pixels'] for r in rs)}/{len(rs)}, "
                         f"reader {sum(r['reader'] for r in rs)}/{len(rs)}", "viewcheck/viewcheck.json"))
    rows.append(("cue score is model-free", "5 templates x 2 orders", "8 cells on built pages", "none",
                 "A, A2, C, E cue 1 in 10/10 each; B, B2, OFF, ZERO cue 0 in 10/10 each", "web/logs/cue_realpages.log"))
    head = ("# Proof matrix: hiding-vs-stacked\n\nGenerated by `proof_matrix.py` from `results/analysis_counted.json`. "
            "Cut = neutral follow rate minus stacked-counter follow rate; brackets are 95% bootstrap intervals "
            "(PREREG s5).\n\n| claim | seed | variant | control | result | artifact |\n|---|---|---|---|---|---|\n")
    body = "".join("| " + " | ".join(str(x).replace("|", "/") for x in r) + " |\n" for r in rows)
    path = ROOT / "proof-matrix.md"
    tail = ""
    if path.exists() and MARK in path.read_text():
        tail = path.read_text().split(MARK, 1)[1]
    path.write_text(head + body + "\n" + MARK + tail)
    print(f"{len(rows)} rows -> {path}")


if __name__ == "__main__":
    main()
