"""Write proof-matrix.md from results.json (+ secondary files). One row per (claim, seed, variant, control).

    .venv/bin/python proof_matrix.py
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np

HERE = Path(__file__).parent
BLIND = ["24x24x12r3", "24x24x12r6", "48x48x8r2", "20x20x10r5", "40x24x12r4"]


def share(misses):
    m = np.asarray(misses)
    return f"{(m <= 5).mean():.2f} within 5 pts (n {len(m)}), median miss {np.median(m):.2f}"


def main():
    R = json.loads((HERE / "results.json").read_text())
    cells = R["cells"]
    prim = [c for c in cells if c["primary"]]
    p = R["primary"]
    L = []
    L.append("# Proof matrix: llc-bias-law\n")
    L.append(f"Generated by proof_matrix.py from results.json (score.py; prereg {R['prereg_commit']}). "
             "e = relative error of the learning-coefficient estimate; miss = |predicted e - measured e| in points.\n")
    L.append(f"STATUS (frozen rule 2(6)): **{p['status']}** ({p['why']}); law L share within 5 points "
             f"{p['L']['share_within_5']:.3f} over {p['L']['n']} primary cells, median miss {p['L']['median_miss']:.2f}, "
             f"spread {p['spread_pts']:.1f} points.\n")
    sl = p["seed_level"]
    L.append(f"seed-level: {sl['mean']:.3f} [{sl['ci95'][0]:.3f}, {sl['ci95'][1]:.3f}] ({sl['method']}; "
             f"per seed {', '.join(f'{x:.3f}' for x in sl['per_seed'])})\n")
    L.append("| claim | seed | variant | control | result | artifact |")
    L.append("|---|---|---|---|---|---|")
    for shp in BLIND:
        cs = [c for c in prim if c["case"] == shp]
        for sd in ("0", "1", "2"):
            m = [100.0 if (not c["converged"] or c["e_seeds"].get(sd) is None or not math.isfinite(c["e_seeds"][sd]))
                 else 100 * abs(c["pred"]["L"] - c["e_seeds"][sd]) for c in cs]
            L.append(f"| headline | {sd} | {shp}, arm S, 36 primary settings | none | law L {share(m)} | "
                     f"data/cells_S/{shp}.json |")
    for shp in BLIND:
        cs = [c for c in prim if c["case"] == shp]
        m = [100.0 if not c["converged"] else 100 * abs(c["pred"]["L"] - c["e_meas"]) for c in cs]
        L.append(f"| headline | mean of 3 | {shp}, seed-mean | none | law L {share(m)} | results.json |")
    for law in ("N1", "N2", "N3", "N4"):
        v = p["nulls"][law]
        L.append(f"| headline | mean of 3 | all 5 blind shapes | null {law} (fit on train only) | share "
                 f"{v['share_within_5']:.2f}, median miss {v['median_miss']:.2f} (law L {p['L']['median_miss']:.2f}) | "
                 f"predictions.json, results.json |")
    sec = R.get("secondary", {})
    if "error_split" in sec:
        es = sec["error_split"]
        L.append(f"| target vs sampler | 0,1 (Gibbs) | all primary cells | exact block Gibbs (no step size) | median "
                 f"|target bias| {es['median_abs_target_pts']:.1f} pts, median |SGLD - Gibbs| "
                 f"{es['median_abs_sampler_pts']:.2f} pts, max {es['max_abs_sampler_pts']:.1f} | data/gibbs_S/ |")
    if "S3_armP_primary" in sec:
        v = sec["S3_armP_primary"]
        L.append(f"| arm P control | 0,1 | 5 blind shapes, full-gradient Langevin | population loss, no minibatch | "
                 f"share {v['share_within_5']:.2f}, median {v['median_miss']:.2f} | data/cells_P/ |")
    for k, lab in (("S6_seen", "pilot-seen shapes (not blind)"), ("control_16x16x8r8", "all-regular control (16,16,8) r8"),
                   ("S4_strong_spring_blind", "blind shapes, q < 0.1 (S4)"), ("L_z_primary", "law L_z (secondary)")):
        if k in sec:
            v = sec[k]
            L.append(f"| {k} | mean of 3 | {lab} | {'lambda0 = 0' if 'control' in k else 'none'} | share "
                     f"{v['share_within_5']:.2f}, median {v['median_miss']:.2f} (n {v['n']}) | results.json |")
    s = R["sensitivity_without_24x24x12r3"]
    L.append(f"| sensitivity | mean of 3 | blind core without (24,24,12) r3 (disclosed smoke peek) | none | "
             f"{s['status']}, share {s['L']['share_within_5']:.3f} | results.json |")
    (HERE / "proof-matrix.md").write_text("\n".join(L) + "\n")
    print("\n".join(L[:6]))


if __name__ == "__main__":
    main()
