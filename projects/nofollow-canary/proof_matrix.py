"""results/analysis.json + results/analysis_runs.csv -> proof-matrix.md. Lines after the SKEPTIC marker are kept.

    uv run python proof_matrix.py

Seeds = the pre-registered seed blocks b = i mod 3 (s0, s1, s2; run-index groups with their own run seeds, no
training). Headline rows: the five status arms per seed block, and the two one-change differences of the CONFIRMED
rule (rawnf minus raw, mdhtml minus mdnf) per block. Pooled rows (seed '-') carry the run-level Newcombe intervals and
the status. Controls: the link-syntax control (mdhtml), the reference format (md), the skill gate (md view, unscored)
and the length dose (mdpad8), each per block. Every artifact cell is ONE path relative to this folder; no '|' in a cell.
"""
from __future__ import annotations

import ast
import csv
import json
import re
from pathlib import Path

PROJ = Path(__file__).resolve().parent
MARK = "<!-- SKEPTIC ROWS: everything below this line is kept by proof_matrix.py -->"
OUT = "web/out/qwen3-8b/raw"
ARM_TEXT = {"raw": "raw HTML (canary has rel=nofollow)", "rawnf": "raw HTML minus rel=nofollow",
            "md": "markdown", "mdhtml": "markdown, slot links as inline HTML a-tags",
            "mdnf": "markdown, inline a-tags plus rel=nofollow", "mdpad8": "markdown padded to 8x raw tokens"}
CONTROL = {"raw": "none", "rawnf": "none", "mdnf": "none", "md": "reference format",
           "mdhtml": "link-syntax control", "mdpad8": "length dose"}
DIFFS = {"rawnf-raw": "rawnf minus raw", "mdhtml-mdnf": "mdhtml minus mdnf", "md-rawnf": "md minus rawnf",
         "mdnf-raw": "mdnf minus raw"}


def f3(x: float, signed: bool = False) -> str:
    return "n/a" if x is None else (f"{x:+.3f}" if signed else f"{x:.3f}")


def main() -> None:
    res = json.loads((PROJ / "results" / "analysis.json").read_text())
    runs = list(csv.DictReader((PROJ / "results" / "analysis_runs.csv").open()))
    pa = res["arms"]
    out = ["# Proof matrix — nofollow-canary", "",
           f"Generated by `proof_matrix.py` from `results/analysis.json` (status {res['status']}). Seeds are the",
           "pre-registered seed blocks b = i mod 3 (s0, s1, s2): run-index groups with their own run seeds (no training).",
           "", "| claim | seed | variant | control | result | artifact |", "|---|---|---|---|---|---|"]

    def block(arm: str, b: int) -> tuple[int, int]:
        rs = [r for r in runs if r["arm"] == arm and r.get("scored") == "True" and int(r["i"]) % 3 == b]
        return sum(int(r["follow"]) for r in rs), len(rs)

    for arm in ("raw", "rawnf", "md", "mdhtml", "mdnf"):
        claim = "headline" if CONTROL[arm] == "none" else "control"
        for b in range(3):
            f, n = block(arm, b)
            out.append(f"| {claim} | s{b} | {ARM_TEXT[arm]} | {CONTROL[arm]} | followed {f} of {n} | {OUT}/{arm}-free |")
        w = pa[arm]["wilson"]
        out.append(f"| pooled | - | {ARM_TEXT[arm]} | {CONTROL[arm]} | followed {pa[arm]['follow']} of {pa[arm]['n']} = "
                   f"{f3(pa[arm]['catch'])} [{f3(w[0])}, {f3(w[1])}] (Wilson 95%) | results/analysis.json |")
    for key, name in DIFFS.items():
        sl = res["seed_level"][key]
        for b, d in enumerate(sl["blocks"]):
            out.append(f"| headline | s{b} | {name} | none | {f3(d, True)} | results/analysis.json |")
        d = res["differences"][key]
        out.append(f"| pooled | - | {name} | none | {f3(d['diff'], True)} [{f3(d['lower'], True)}, {f3(d['upper'], True)}] "
                   f"(Newcombe 95%) | results/analysis.json |")
    for b in range(3):
        f, n = block("mdpad8", b)
        out.append(f"| length | s{b} | {ARM_TEXT['mdpad8']} | length dose | followed {f} of {n} | {OUT}/mdpad8-free |")
    gate = [r for r in runs if r["arm"] == "gate" and r.get("scored") == "True"]
    for b in range(3):
        g = [r for r in gate if int(r["i"]) % 3 == b]
        ok = sum(1 for r in g if r["follow"] == "1" and r.get("correct") == "1")
        out.append(f"| control | s{b} | skill gate, markdown view | skill gate (unscored) | {ok} of {len(g)} followed and "
                   f"answered | {OUT}/gatemd-free |")
    out.append(f"| status | - | frozen rule | none | {res['status']}; gates {' '.join(k + '=' + str(v) for k, v in res['gates'].items())} "
               f"| results/analysis.json |")
    # Skeptic rebuild (Vera, own code from access.log + raw/*.json): one row per status arm and seed block, read from
    # her output file; a block that differs from ours is marked MISMATCH. Her arm-shuffle null is a control row.
    reb = PROJ / "skeptics" / "skeptic" / "out_rebuild.txt"
    if reb.exists():
        rel = "skeptics/skeptic/out_rebuild.txt"
        text = reb.read_text()
        for arm in ("raw", "rawnf", "md", "mdhtml", "mdnf"):
            m = re.search(rf"^{arm}\s+\d+\s+(\d+)\s+(\d+)\s.*?(\{{.*\}})\s*$", text, re.M)
            blocks = ast.literal_eval(m.group(3))
            for b in range(3):
                fv, nv = blocks[b]
                mark = "" if (fv, nv) == block(arm, b) else " MISMATCH"
                out.append(f"| rebuild | s{b} | {ARM_TEXT[arm]} | none | followed {fv} of {nv} (Vera's code){mark} | {rel} |")
        m = re.search(r"^NULL \(([^)]*)\): (\{.*\})\s*$", text, re.M)
        if m:
            null = ast.literal_eval(m.group(2))
            tot = sum(null.values())
            out.append(f"| rebuild | - | frozen rule on arm labels shuffled within site ({tot} draws) | shuffled arm labels | "
                       f"{', '.join(f'{k} {v}' for k, v in null.items())} | {rel} |")
    out.append("")
    for key, name in DIFFS.items():
        sl = res["seed_level"][key]
        if sl["mean"] is not None:
            out.append(f"- seed-level: {name} {sl['mean']:+.3f} [{sl['lower']:+.3f}, {sl['upper']:+.3f}] "
                       f"(t-interval over 3 seed blocks, df 2)")
    out += ["", MARK]
    path = PROJ / "proof-matrix.md"
    old = path.read_text() if path.exists() else ""
    tail = old.split(MARK, 1)[1] if MARK in old else "\n"
    path.write_text("\n".join(out) + tail)
    print("wrote", path)


if __name__ == "__main__":
    main()
