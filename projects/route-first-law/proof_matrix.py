"""Write proof-matrix.md from results/analysis.json (and the skeptics' rebuild outputs when they exist).

    uv run python proof_matrix.py

One row per cell: claim x seed block x variant (harness / arm / model) x control. 'seed' = the seed block (run index
mod 3): a group of runs with its own sampling seeds; no model is trained. NONE (no route in the page or denial) is the
control arm of each harness. Headline rows = the pooled BEFORE and AFTER cells the status rests on, per seed block.
"""
from __future__ import annotations

import csv
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent
ARMS = ("none", "before", "after")
RUNS: list[dict] = []
HARNESSES = ("web", "shell")
LABEL = {"web": "web canary", "shell": "shell decoy key"}
POS = {"none": "NONE (no route)", "before": "BEFORE (route above decoy)", "after": "AFTER (route below decoy)"}


def cell_file(h: str, arm: str, who: str, b: str, data: dict) -> str:
    """Write one proof-matrix cell as its own JSON (counts + the run files it counts) and return its path."""
    rows = [r for r in RUNS if r["harness"] == h and r["arm"] == arm and (who == "pooled" or r["model"] == who)
            and (b == "all" or int(r["seed_block"]) == int(b))]
    rel = f"results/cells/{h}_{arm}_{who}_b{b}.json"
    (ROOT / rel).parent.mkdir(parents=True, exist_ok=True)
    (ROOT / rel).write_text(json.dumps({"harness": h, "arm": arm, "model": who, "seed_block": b, "cell": data,
                                        "runs": [{"model": r["model"], "i": int(r["i"]), "exposed": r["exposed"] == "True",
                                                  "trap": r["trap"] == "True",
                                                  "file": f"data/main/{r['model']}/{h}/raw/{arm}/{int(r['i']):03d}.json"}
                                                 for r in rows]}, indent=1) + "\n")
    return rel


def fmt(k: int, n: int) -> str:
    return f"{k}/{n} = {k / n:.3f}" if n else f"{k}/0"


def skeptic_rows(res: dict) -> list[str]:
    """Rows from the skeptics' own rebuilds, parsed from their outputs; MISMATCH marks a cell that differs from ours."""
    import re
    out = []
    reb = ROOT / "skeptics" / "skeptic" / "out_rebuild.txt"
    if reb.exists():
        h = None
        for line in reb.read_text().splitlines():
            m = re.match(r"== (web|shell):", line)
            if m:
                h = m.group(1)
                continue
            m = re.match(r"\s+(none|before|after)\s+(\d+)/(\d+) .*?per-model 31b: (\d+)/(\d+), 26b: (\d+)/(\d+)", line)
            if h and m:
                arm, k, n = m.group(1), int(m.group(2)), int(m.group(3))
                P = res["pooled"][h][arm]
                same = (k, n) == (P["trap"], P["n_exposed"])
                pm = res["per_model"]
                same_m = ((int(m.group(4)), int(m.group(5))) == (pm["gemma-4-31b-it"][h][arm]["trap"], pm["gemma-4-31b-it"][h][arm]["n_exposed"])
                          and (int(m.group(6)), int(m.group(7))) == (pm["gemma-4-26b-a4b-it"][h][arm]["trap"], pm["gemma-4-26b-a4b-it"][h][arm]["n_exposed"]))
                out.append(f"| rebuild (Vera, own parser) | all | {LABEL[h]} / {POS[arm]} / pooled + per model | "
                           f"{'none' if arm != 'none' else 'no-route arm (NONE)'} | trap {fmt(k, n)}; 31B {m.group(4)}/{m.group(5)}, "
                           f"26B {m.group(6)}/{m.group(7)}; {'MATCH' if same and same_m else 'MISMATCH'} vs analysis.json | "
                           f"skeptics/skeptic/out_rebuild.txt |")
    nul = ROOT / "skeptics" / "skeptic" / "out_null.txt"
    if nul.exists():
        for line in nul.read_text().splitlines():
            m = re.match(r"== (web|shell): .*?gap (-?[\d.]+).*?McNemar exact p ([\d.e-]+); label-swap permutation p ([\d.e-]+)", line)
            if m:
                out.append(f"| null: BEFORE/AFTER labels swapped within run index (Vera) | - | {LABEL[m.group(1)]} / pooled | "
                           f"label-swap permutation | AFTER minus BEFORE gap {m.group(2)}; permutation p {m.group(4)}; "
                           f"exact McNemar p {m.group(3)} | skeptics/skeptic/out_null.txt |")
    return out


def main() -> None:
    global RUNS
    res = json.loads((ROOT / "results" / "analysis.json").read_text())
    with (ROOT / "results" / "analysis_runs.csv").open() as f:
        RUNS = list(csv.DictReader(f))
    R = res["rule"]
    lines = ["# Proof matrix — route-first-law", "",
             "Generated by `proof_matrix.py` from `results/analysis.json` (`analysis.py` over `data/main/`). Trap rate = runs",
             "that used the decoy / exposed runs. Seed = seed block b = run index mod 3 (its own sampling seeds; no model is",
             "trained). Artifacts are paths relative to this folder; every run file is `data/main/<model>/<harness>/raw/<arm>/<NNN>.json`.",
             "",
             f"**Status (frozen rule, PREREG section 3): {R['status']}**; prediction v2: {R['prediction_v2']}.", ""]
    for h in HARNESSES:
        H = R["harness"][h]
        lines.append(f"- {LABEL[h]}: valid {H['valid']} (complete n {H['complete_n']}, all blocks {H['all_blocks']}, "
                     f"exposure >= 90% {H['exposure_ok']}, NONE >= 75% {H['none_ok']}); C1 {H['C1']}, C2 {H['C2']}; "
                     f"reject C1 {H['reject_C1']}, reject C2 {H['reject_C2']}; guard hits: {H['guard_hits'] or 'none'}.")
    lines.append("")
    for h in HARNESSES:
        for arm in ("before", "after"):
            P = res["pooled"][h][arm]
            sl = P["seed_level"]
            lines.append(f"seed-level: {LABEL[h]} {arm.upper()} {sl['mean']:.3f} [{sl['low']:.3f}, {sl['high']:.3f}] "
                         f"(t-interval over 3 seed blocks, df 2; run-level Wilson [{P['wilson'][0]:.3f}, {P['wilson'][1]:.3f}], "
                         f"{P['trap']}/{P['n_exposed']})")
    lines += ["", "| claim | seed | variant | control | result | artifact |", "|---|---|---|---|---|---|"]
    for h in HARNESSES:
        for arm in ARMS:
            P = res["pooled"][h][arm]
            claim = "headline" if arm != "none" else "validity: NONE >= 75%"
            control = "none" if arm != "none" else "no-route arm (NONE)"
            for b in range(3):
                B = P["seed_blocks"][str(b)] if str(b) in P["seed_blocks"] else P["seed_blocks"][b]
                lines.append(f"| {claim} | {b} | {LABEL[h]} / {POS[arm]} / pooled 2 models | {control} | trap {fmt(B['trap'], B['n_exposed'])} (analysis.json pooled.{h}.{arm}.seed_blocks.{b}) | "
                             f"{cell_file(h, arm, 'pooled', str(b), B)} |")
            lines.append(f"| {claim} | all (3 blocks) | {LABEL[h]} / {POS[arm]} / pooled 2 models | {control} | trap {fmt(P['trap'], P['n_exposed'])}, "
                         f"Wilson [{P['wilson'][0]:.3f}, {P['wilson'][1]:.3f}], exposure {P['n_exposed']}/{P['n']} (analysis.json pooled.{h}.{arm}) | {cell_file(h, arm, 'pooled', 'all', P)} |")
    for h in HARNESSES:
        for arm in ARMS:
            for m, M in res["per_model"].items():
                M = M[h][arm]
                claim = "guard (per model)" if arm != "none" else "validity per model"
                control = "none" if arm != "none" else "no-route arm (NONE)"
                for b in range(3):
                    B = M["seed_blocks"][str(b)] if str(b) in M["seed_blocks"] else M["seed_blocks"][b]
                    lines.append(f"| {claim} | {b} | {LABEL[h]} / {POS[arm]} / {m} | {control} | trap {fmt(B['trap'], B['n_exposed'])} (i mod 3 = {b}) | "
                                 f"{cell_file(h, arm, m, str(b), B)} |")
                lines.append(f"| {claim} | all | {LABEL[h]} / {POS[arm]} / {m} | {control} | trap {fmt(M['trap'], M['n_exposed'])}, "
                             f"Wilson [{M['wilson'][0]:.3f}, {M['wilson'][1]:.3f}] (analysis.json per_model.{m}.{h}.{arm}) | {cell_file(h, arm, m, 'all', M)} |")
    S = res["secondary"]
    for h in HARNESSES:
        cf = S["competitor_first"][h]
        pr = S["paired"][h]
        lines.append(f"| secondary: per-run competitor-first label | - | {LABEL[h]} / all arms / pooled | none | "
                     f"competitor-first trap {fmt(cf['cf_trap'], cf['cf_n'])}; other {fmt(cf['other_trap'], cf['other_n'])} (analysis.json secondary.competitor_first) | results/analysis.json |")
        lines.append(f"| secondary: paired BEFORE vs AFTER (same run index) | - | {LABEL[h]} / pooled | none | "
                     f"trap only BEFORE {pr['before_only']}, only AFTER {pr['after_only']}, both {pr['both']}, neither {pr['neither']}; "
                     f"exact McNemar p {pr['mcnemar_exact_p']:.3g} (analysis.json secondary.paired) | results/analysis.json |")
    lines.append(f"| check: web trap from access.log = raw harness_followed | - | web / all | none | "
                 f"{res['web_log_vs_raw_mismatch']} mismatches (columns trap vs trap_raw) | results/analysis_runs.csv |")
    tests = ROOT / "results" / "test_arms.txt"
    if tests.exists():
        lines.append(f"| check: arms differ only by the moved route item | - | web + shell / harness | none | {tests.read_text().strip()} | results/test_arms.txt |")
    lines += skeptic_rows(res)
    extra = ROOT / "skeptics" / "proof-rows.md"
    if extra.exists():
        lines += [l for l in extra.read_text().splitlines() if l.startswith("| ")]
    (ROOT / "proof-matrix.md").write_text("\n".join(lines) + "\n")
    print(f"proof-matrix.md: {sum(l.startswith('| ') for l in lines) - 1} rows")


if __name__ == "__main__":
    main()
