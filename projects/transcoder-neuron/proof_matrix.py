"""proof-matrix.md from data/status.json (+ gate files). Keeps rows below the SKEPTIC marker line.

  env/.venv/bin/python proof_matrix.py
"""
import json
import os

S = json.load(open("data/status.json"))
G = json.load(open("data/gate.json"))
G7 = json.load(open("data/gate_graph_L8.json"))
f = lambda x: "nan" if x is None else f"{x:.3f}"
rows = []
A = "data/status.json"
for L, cells in S["cells"].items():
    raw = f"data/pushes/L{L}_pushes.csv"
    for g in ["NEURON", "REST"]:
        c = cells[g]
        for s, v in enumerate(c["R2_seed"]):
            rows.append(("headline", s, f"L{L} {g} READ TOTAL vs MLP (g_real)", "none", f"R2 {f(v)}", raw))
        rows.append(("headline", "pooled", f"L{L} {g} READ", "none",
                     f"R2 {f(c['R2'])} CI [{f(c['R2_ci'][0])}, {f(c['R2_ci'][1])}], n={c['n_units']} units", A))
    ly = S["layers"][L]
    rows.append(("headline", "all", f"L{L} layer verdict", "none",
                 f"{ly['verdict']} (seeds {ly['seed_verdicts']}; clause {ly['no_clause']})", A))
    rows.append(("defined gate", "all", f"L{L} local read-out vs real end-to-end", "read-out check",
                 f"R2 {f(ly['defined_R2'])} ({'pass' if ly['defined'] else 'FAIL'})", A))
    rows.append(("precision", "all", f"L{L} full vs cached forward", "du = 0",
                 f"max {ly['precision_maxabs_full_vs_cache']:.2e} vs 1% median {ly['precision_1pct_median_e2e']:.2e}", A))
    rows.append(("gap null", "all", f"L{L} NEURON-REST gap", "class-label shuffle (1000)",
                 f"gap {f(ly['gap'])}, null 95% [{f(ly['gap_shuffle_null_95'][0])}, {f(ly['gap_shuffle_null_95'][1])}], p {ly['gap_shuffle_p_two_sided']:.3f}", A))
    for g in ["NEURON", "GAP", "REST", "ORACLE"]:
        c = cells[g]
        rows.append(("reference", "pooled", f"L{L} {g}", "random push at matched |du|", f"R2 {f(c['R2_rnd_push'])}", raw))
        rows.append(("theory (Pred C)", "pooled", f"L{L} {g}", "none", f"R2_theory {f(c['R2_theory'])} vs measured {f(c['R2'])}", raw))
        rows.append(("f-only node claim", "pooled", f"L{L} {g}", "none", f"R2 {f(c['R2_fonly'])}", raw))
        rows.append(("floor", "pooled", f"L{L} {g}", "random decoder at |d|", f"R2 {f(c['R2_floor'])}", raw))
        rows.append(("graph read-out", "pooled", f"L{L} {g}", "none", f"R2 graph-g pred vs real e2e {f(c['R2_graph_vs_e2e'])}", raw))
        rows.append(("WRITE (v1)", "pooled", f"L{L} {g}", "none",
                     f"R2 graph-g {f(c['R2_write_plus_graph'])}, real-g {f(c['R2_write_plus_real'])}; random dir real-g {f(c['R2_write_rnd_plus_real'])}", raw))
    c = cells["ORACLE"]
    rows.append(("known answer", "pooled", f"L{L} real neuron as feature", "oracle neuron", f"R2 {f(c['R2'])}", raw))
B = S["predB"]
rows.append(("law (Pred B)", "all", "partial Spearman joint cos vs per-feature error, READ", "5 covariates",
             f"{f(B['read_partial'])}; WRITE {f(B['write_partial_real_g'])}; {B['outcome']}", A))
rows.append(("Pred C", "all", "12 cells within 0.15", "none", f"{S['predC']['cells_within_0.15']}/12 {S['predC']['outcome']}", A))
rows.append(("engine G1", "-", "own forward vs HF logits", "none", f"max |dlogit| {G['G1_maxabs_logit_diff_vs_HF']:.1e}", "data/gate.json"))
rows.append(("engine G5", "-", "chunked frozen-error grad vs explicit", "none", f"rel {G['G5_TCLin_vs_explicit_relerr']:.1e}", "data/gate.json"))
rows.append(("engine G6", "-", "real grad vs finite difference", "none", f"max rel {G['G6_grad_vs_fd_maxrel']:.1e}", "data/gate.json"))
rows.append(("engine G7", "-", "graph g vs FD in explicitly frozen model", "none",
             f"median rel {G7['fd_h1e-2_vs_ggraph_dt_median_rel']:.3f}", "data/gate_graph_L8.json"))
head = "| claim | seed | variant | control | result | artifact |\n|---|---|---|---|---|---|\n"
body = "".join(f"| {a} | {b} | {c} | {d} | {e} | {g} |\n" for a, b, c, d, e, g in rows)
MARK = "<!-- SKEPTIC ROWS BELOW (kept by proof_matrix.py) -->"
keep = ""
if os.path.exists("proof-matrix.md"):
    t = open("proof-matrix.md").read()
    if MARK in t:
        keep = t[t.index(MARK) + len(MARK):]
open("proof-matrix.md", "w").write(f"# Proof matrix: transcoder-neuron\n\nGenerated by proof_matrix.py from data/status.json "
                                   f"(status {S['status']}).\n\n" + head + body + "\n" + MARK + keep)
print(len(rows), "rows")
